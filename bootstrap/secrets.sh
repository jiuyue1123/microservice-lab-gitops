#!/usr/bin/env bash
# Creates the bootstrap Secrets required by the microservice-lab platform.
# Safe to re-run: existing Secrets are never rotated.

set -euo pipefail
umask 077

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SECRETS_FILE="${REPO_ROOT}/.secrets.env"

command -v kubectl >/dev/null 2>&1 || { echo "ERROR: kubectl not found" >&2; exit 1; }
command -v openssl >/dev/null 2>&1 || { echo "ERROR: openssl not found" >&2; exit 1; }

echo "Using kubectl context: $(kubectl config current-context)"
kubectl apply -k "${REPO_ROOT}/infrastructure/namespaces" >/dev/null

gen_hex() { openssl rand -hex "${1:-24}"; }
gen_b64() { openssl rand -base64 "${1:-32}" | tr -d '\n'; }

secret_exists() {
  kubectl -n "$1" get secret "$2" >/dev/null 2>&1
}

ensure_secret() {
  local ns="$1" name="$2"
  shift 2

  if secret_exists "$ns" "$name"; then
    echo "Exists, skipping: ${ns}/${name}"
    local kv key
    for kv in "$@"; do
      key="${kv%%=*}"
      if ! kubectl -n "$ns" get secret "$name" -o jsonpath="{.data.${key}}" 2>/dev/null | grep -q .; then
        echo "  WARNING: ${ns}/${name} is missing key '${key}'; not modifying it." >&2
      fi
    done
    return
  fi

  local args=() kv
  for kv in "$@"; do
    args+=(--from-literal="$kv")
  done
  kubectl -n "$ns" create secret generic "$name" "${args[@]}" \
    --dry-run=client -o yaml | kubectl apply -f - >/dev/null
  echo "Created: ${ns}/${name}"
}

ensure_secret microservice-lab-platform mysql-auth-credentials \
  "mysql-root-password=$(gen_hex 24)" \
  "mysql-password=$(gen_hex 24)" \
  "mysql-database=auth_db" \
  "mysql-username=auth"

ensure_secret microservice-lab-platform mysql-order-credentials \
  "mysql-root-password=$(gen_hex 24)" \
  "mysql-password=$(gen_hex 24)" \
  "mysql-database=order_db" \
  "mysql-username=order"

ensure_secret microservice-lab-platform mysql-tenant-credentials \
  "mysql-root-password=$(gen_hex 24)" \
  "mysql-password=$(gen_hex 24)" \
  "mysql-database=tenant_db" \
  "mysql-username=tenant"

ensure_secret microservice-lab-platform mysql-user-credentials \
  "mysql-root-password=$(gen_hex 24)" \
  "mysql-password=$(gen_hex 24)" \
  "mysql-database=user_db" \
  "mysql-username=user"

ensure_secret microservice-lab-platform mysql-nacos-credentials \
  "mysql-root-password=$(gen_hex 24)" \
  "mysql-password=$(gen_hex 24)" \
  "mysql-database=nacos" \
  "mysql-username=nacos"

ensure_secret microservice-lab-platform redis-credentials \
  "redis-password=$(gen_hex 24)"

ensure_secret microservice-lab-platform rabbitmq-credentials \
  "rabbitmq-password=$(gen_hex 24)" \
  "rabbitmq-erlang-cookie=$(gen_hex 32)"

ensure_secret microservice-lab-platform nacos-secrets \
  "auth-token=$(gen_b64 32)" \
  "auth-identity-key=$(gen_hex 16)" \
  "auth-identity-value=$(gen_hex 16)"

ensure_secret microservice-lab-platform nacos-client-credentials \
  "username=mslab" \
  "password=$(gen_hex 24)"

ensure_secret microservice-lab-platform jwt-secret \
  "jwt-secret=$(gen_b64 32)"

read_secret() {
  kubectl -n "$1" get secret "$2" -o jsonpath="{.data.$3}" | base64 -d
}

{
  echo "# Generated by bootstrap/secrets.sh - DO NOT COMMIT"
  echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for svc in auth order tenant user nacos; do
    upper=$(echo "$svc" | tr '[:lower:]' '[:upper:]')
    echo "MYSQL_${upper}_ROOT_PASSWORD=$(read_secret microservice-lab-platform "mysql-${svc}-credentials" mysql-root-password)"
    echo "MYSQL_${upper}_PASSWORD=$(read_secret microservice-lab-platform "mysql-${svc}-credentials" mysql-password)"
    echo "MYSQL_${upper}_DATABASE=$(read_secret microservice-lab-platform "mysql-${svc}-credentials" mysql-database)"
    echo "MYSQL_${upper}_USERNAME=$(read_secret microservice-lab-platform "mysql-${svc}-credentials" mysql-username)"
  done
  echo "REDIS_PASSWORD=$(read_secret microservice-lab-platform redis-credentials redis-password)"
  echo "RABBITMQ_PASSWORD=$(read_secret microservice-lab-platform rabbitmq-credentials rabbitmq-password)"
  echo "RABBITMQ_ERLANG_COOKIE=$(read_secret microservice-lab-platform rabbitmq-credentials rabbitmq-erlang-cookie)"
  echo "NACOS_AUTH_TOKEN=$(read_secret microservice-lab-platform nacos-secrets auth-token)"
  echo "NACOS_AUTH_IDENTITY_KEY=$(read_secret microservice-lab-platform nacos-secrets auth-identity-key)"
  echo "NACOS_AUTH_IDENTITY_VALUE=$(read_secret microservice-lab-platform nacos-secrets auth-identity-value)"
  echo "NACOS_CLIENT_USERNAME=$(read_secret microservice-lab-platform nacos-client-credentials username)"
  echo "NACOS_CLIENT_PASSWORD=$(read_secret microservice-lab-platform nacos-client-credentials password)"
  echo "JWT_SECRET=$(read_secret microservice-lab-platform jwt-secret jwt-secret)"
} > "${SECRETS_FILE}"
chmod 600 "${SECRETS_FILE}"

echo
echo "Secrets are present in the cluster."
echo "Local reference written to ${SECRETS_FILE} (gitignored)."
